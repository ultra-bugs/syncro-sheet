use Zuko\SyncroSheet\Services\TrackingDatabase;

/**
 * Tracking models live on the connection resolved by TrackingDatabase
 * (dedicated SQLite, a configured connection, or the app default).
 */
trait UsesTrackingConnection
{
    public function getConnectionName()
    {
        return TrackingDatabase::connectionName() ?? parent::getConnectionName();
    }
}
